import { chromium } from './node_modules/.pnpm/playwright@1.49.1/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1610, height: 1043 }, deviceScaleFactor: 1 });
await page.goto('http://localhost:5002/#/home', { waitUntil: 'networkidle' });
console.log('URL:', page.url());
console.log('TITLE:', await page.title());
console.log('INPUTS:', await page.locator('input').evaluateAll(nodes => nodes.map(n => ({ type: n.type, name: n.name, placeholder: n.placeholder, id: n.id }))));
console.log('BUTTONS:', await page.locator('button').evaluateAll(nodes => nodes.map(n => (n.textContent || '').trim()).filter(Boolean).slice(0, 20)));
console.log('BODY:', (await page.locator('body').innerText()).slice(0, 800));
await page.screenshot({ path: '/tmp/checkapp-login.png', fullPage: false });
await browser.close();

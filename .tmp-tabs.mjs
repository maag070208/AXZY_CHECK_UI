import { chromium } from './node_modules/.pnpm/playwright@1.49.1/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1610, height: 1043 }, deviceScaleFactor: 1 });
await page.goto('http://localhost:5002/#/login', { waitUntil: 'networkidle' });
await page.fill('#username', 'aamaro');
await page.fill('#password', '123456');
await page.click('button:has-text("Iniciar Sesión")');
await page.waitForTimeout(4500);
await page.evaluate(() => window.scrollTo(0, 0));
await page.getByRole('button', { name: /Security Analytics/ }).click();
await page.waitForTimeout(2500);
console.log('ANALYTICS URL:', page.url());
console.log('ANALYTICS TEXT:', (await page.locator('body').innerText()).slice(0, 500));
const inputs = await page.locator('input').evaluateAll(nodes => nodes.map(n => ({ name: n.name, value: n.value, placeholder: n.placeholder, type: n.type })));
console.log('INPUTS:', JSON.stringify(inputs));
const metrics = await page.evaluate(() => {
  const h = [...document.querySelectorAll('h2,h3')].find(e => (e.textContent||'').trim() === 'Security Analytics');
  const card = [...document.querySelectorAll('h3')].find(e => (e.textContent||'').includes('Top Desempeño'));
  const r1 = h?.getBoundingClientRect(); const r2 = card?.getBoundingClientRect();
  return { heading: r1 ? {x: Math.round(r1.x), y: Math.round(r1.y), w: Math.round(r1.width)} : null, topCard: r2 ? {x: Math.round(r2.x), y: Math.round(r2.y), w: Math.round(r2.width)} : null };
});
console.log('METRICS:', JSON.stringify(metrics));
await page.screenshot({ path: '/tmp/checkapp-analytics.png', fullPage: false });
await page.getByRole('button', { name: /^Monitoreo$/ }).click();
await page.waitForTimeout(1000);
await page.getByRole('button', { name: /Ritmo de la operación/ }).click();
await page.waitForTimeout(1000);
await page.screenshot({ path: '/tmp/checkapp-ritmo.png', fullPage: false });
await browser.close();
